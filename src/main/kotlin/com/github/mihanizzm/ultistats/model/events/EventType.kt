package com.github.mihanizzm.ultistats.model.events

enum class EventType(
    val readableName: String,
    val category: EventCategory,
) {
    /** Успешный пас от текущего владельца партнёру. Получатель становится владельцем диска. */
    PASS("Пас", EventCategory.TWO_PLAYER),

    /**
     * Успешный пас, пойманный партнёром в атакуемой голевой зоне. Бросающему записываются пас и ассист,
     * принимающему — ловля и гол; поинт завершается.
     */
    GOAL("Гол", EventCategory.TWO_PLAYER),

    /**
     * Пас текущего владельца, который не был доставлен партнёру без зафиксированного действия защиты:
     * throwaway, выход в аут или неудачная ловля. Незавершённый пас записывается бросающему,
     * а диск остаётся свободным до [PICKUP].
     */
    INCOMPLETE_PASS("Незавершённый пас", EventCategory.ONE_PLAYER),

    /** Ввод диска в игру в начале матча, после завершённого поинта или после halftime. Владельца не устанавливает. */
    PULL("Пулл", EventCategory.ONE_PLAYER),

    /**
     * Объявление brick для непосредственно предшествующего [PULL]. У выполнившего pull игрока увеличивается
     * статистика bricks; диск остаётся свободным до [PICKUP].
     */
    BRICK("Брик", EventCategory.ONE_PLAYER),

    /**
     * Подбор свободного диска после pull, brick, незавершённого паса или блока. Указанный игрок становится
     * владельцем диска; ему и его команде записывается новое владение.
     */
    PICKUP("Подбор диска", EventCategory.ONE_PLAYER),

    /**
     * Блок без уточнения позиции защитника. Первый участник — бросающий, второй — выполнивший блок защитник.
     * Защитнику записывается неуточнённый block; диск остаётся свободным до [PICKUP].
     */
    BLOCK("Блок", EventCategory.TWO_PLAYER),

    /**
     * Уточнённый блок игрока, маркировавшего бросающего. Первый участник — бросающий, второй — защитник.
     * Учитывается только в marker-статистике блоков; диск остаётся свободным до [PICKUP].
     */
    BLOCK_MARKER("Блок на маркере", EventCategory.TWO_PLAYER),

    /**
     * Уточнённый блок полевого защитника. Первый участник — бросающий, второй — защитник. Учитывается только
     * в field-статистике блоков; диск остаётся свободным до [PICKUP].
     */
    BLOCK_FIELD("Полевой блок", EventCategory.TWO_PLAYER),

    /**
     * Защитник ловит пас соперника. Первый участник — бросающий, второй — перехвативший защитник, который сразу
     * становится владельцем диска; дополнительный [PICKUP] не требуется.
     */
    INTERCEPTION("Перехват", EventCategory.TWO_PLAYER),

    /**
     * Защитник перехватывает пас в атакуемой им голевой зоне. Первый участник — бросающий, второй — защитник;
     * событие одновременно учитывает перехват и гол и завершает поинт.
     */
    CALLAHAN("Кэллахан", EventCategory.TWO_PLAYER),

    /** Начало командного таймаута. Останавливает игровой таймер и сохраняет состояние для восстановления. */
    TIMEOUT_START("Начало таймаута", EventCategory.TEAM),

    /** Окончание таймаута. Возобновляет точное состояние, существовавшее до [TIMEOUT_START]. */
    TIMEOUT_END("Конец таймаута", EventCategory.TEAM),

    /** Начало halftime после завершённого поинта. Останавливает игровой таймер. */
    HALFTIME_START("Начало халф-тайма", EventCategory.SYSTEM),

    /** Окончание halftime. Следующий поинт ожидает [PULL]. */
    HALFTIME_END("Конец халф-тайма", EventCategory.SYSTEM),
    ANNOUNCEMENT_START("Начало объявления", EventCategory.ANNOUNCEMENT),
    ANNOUNCEMENT_END("Конец объявления", EventCategory.SYSTEM),
    ;

    fun canReplace(previous: EventType): Boolean =
        this == previous || (this in BLOCK_TYPES && previous in BLOCK_TYPES)

    companion object {
        private val BLOCK_TYPES = setOf(BLOCK, BLOCK_MARKER, BLOCK_FIELD)
    }
}
